// Generates src/lib/db/database.types.ts from a database that has the
// migrations applied. Equivalent in shape to `supabase gen types typescript`.
// Usage: DATABASE_URL=postgresql://... npm run db:types   (requires psql)
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("Set DATABASE_URL to a database with the migrations applied.");
  process.exit(1);
}

function query(sql) {
  const r = spawnSync("psql", [url, "-At", "-v", "ON_ERROR_STOP=1", "-c", sql], { encoding: "utf8" });
  if (r.status !== 0) throw new Error(r.stderr);
  return JSON.parse(r.stdout.trim() || "[]");
}

const columns = query(`
  select coalesce(json_agg(x), '[]') from (
    select c.relname as rel, c.relkind as kind, a.attname as col,
           format_type(a.atttypid, a.atttypmod) as type, not a.attnotnull as nullable,
           (a.atthasdef or a.attidentity <> '' or a.attgenerated <> '') as has_default,
           (a.attgenerated <> '') as generated
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    where n.nspname = 'public' and c.relkind in ('r', 'v')
    order by c.relname, a.attnum) x`);

const functions = query(`
  select coalesce(json_agg(x), '[]') from (
    select p.proname as name,
           coalesce(p.proargnames, '{}') as argnames,
           (select coalesce(json_agg(format_type(t, null)), '[]') from unnest(string_to_array(p.proargtypes::text, ' ')::oid[]) t) as argtypes,
           p.pronargdefaults as ndefaults,
           format_type(p.prorettype, null) as rettype, p.proretset as retset,
           coalesce(p.proargmodes::text[], '{}') as modes,
           (select coalesce(json_agg(format_type(t, null)), '[]') from unnest(coalesce(p.proallargtypes, '{}')) t) as alltypes
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prorettype <> 'trigger'::regtype and p.prokind = 'f'
    order by p.proname) x`);

const SCALARS = {
  uuid: "string", text: "string", date: "string", "character varying": "string", citext: "string", inet: "string",
  "timestamp with time zone": "string", "timestamp without time zone": "string", "time without time zone": "string",
  interval: "string", name: "string", integer: "number", smallint: "number", bigint: "number", numeric: "number",
  "double precision": "number", real: "number", boolean: "boolean", jsonb: "Json", json: "Json",
  void: "undefined", "text[]": "string[]", "uuid[]": "string[]",
};
function ts(type) {
  const base = type.replace(/\(.*\)/, "");
  if (SCALARS[base]) return SCALARS[base];
  if (base.endsWith("[]")) return `${ts(base.slice(0, -2))}[]`;
  return "unknown";
}

const rels = new Map();
for (const c of columns) {
  if (!rels.has(c.rel)) rels.set(c.rel, { kind: c.kind, cols: [] });
  rels.get(c.rel).cols.push(c);
}

let out = `// GENERATED by scripts/gen-db-types.mjs — do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
const views = [];
for (const [rel, { kind, cols }] of rels) {
  const row = cols.map((c) => `          ${c.col}: ${ts(c.type)}${c.nullable ? " | null" : ""};`).join("\n");
  if (kind === "v") {
    views.push(`      ${rel}: {\n        Row: {\n${row}\n        };\n        Relationships: [];\n      };`);
    continue;
  }
  const ins = cols
    .filter((c) => !c.generated)
    .map((c) => `          ${c.col}${c.nullable || c.has_default ? "?" : ""}: ${ts(c.type)}${c.nullable ? " | null" : ""};`)
    .join("\n");
  const upd = cols
    .filter((c) => !c.generated)
    .map((c) => `          ${c.col}?: ${ts(c.type)}${c.nullable ? " | null" : ""};`)
    .join("\n");
  out += `      ${rel}: {\n        Row: {\n${row}\n        };\n        Insert: {\n${ins}\n        };\n        Update: {\n${upd}\n        };\n        Relationships: [];\n      };\n`;
}
out += `    };\n    Views: {\n${views.join("\n")}\n    };\n    Functions: {\n`;
for (const f of functions) {
  const names = f.argnames.slice(0, f.argtypes.length);
  const first = f.argtypes.length - f.ndefaults;
  // SQL function parameters accept NULL, so every argument type allows it.
  const args = f.argtypes.map((t, i) => `${names[i] || `arg${i}`}${i >= first ? "?" : ""}: ${ts(t)} | null`);
  let ret;
  if (f.modes.includes("t")) {
    const outs = [];
    f.modes.forEach((m, i) => { if (m === "t") outs.push(`${f.argnames[i]}: ${ts(f.alltypes[i])}`); });
    ret = `{ ${outs.join("; ")} }[]`;
  } else {
    ret = ts(f.rettype);
    if (f.retset) ret += "[]";
  }
  out += `      ${f.name}: {\n        Args: ${args.length ? `{ ${args.join("; ")} }` : "Record<PropertyKey, never>"};\n        Returns: ${ret};\n      };\n`;
}
out += `    };\n    Enums: Record<string, never>;\n    CompositeTypes: Record<string, never>;\n  };\n};\n`;
writeFileSync("src/lib/db/database.types.ts", out);
console.log(`wrote src/lib/db/database.types.ts (${rels.size} relations, ${functions.length} functions)`);
